-- «Де шукати» з довідника (рішення PO 2026-11-15)
--
-- Підказки «де шукати» (microrefugium_dry / microrefugium_wet) лишились із першого тестового
-- наповнення («Затоплені основи пеньків», «Освітлені пні») — незграбні й не з книг. Замінюємо
-- коротким реченням (до 50 символів, один рядок на картці) за полями «Де росте» / «Порада»
-- книжкових описів (web-guardian/public/mushroom_descriptions.js). Обидва поля однакові:
-- місце гриба не залежить від того, сухо чи волого (вологу пояснює блок погоди).
-- Вовнянка рожева: у книзі поля немає — «під березами» (симбіонт за довідником).
-- ============================================================================

