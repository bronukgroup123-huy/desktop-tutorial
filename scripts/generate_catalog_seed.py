#!/usr/bin/env python3
"""
Генерує SQL seed для mushroom_catalog з mushroom_catalog.json.
- Екранує апострофи в TEXT
- Валідує edibility проти whitelist
- photos → JSONB масив [{url}]
- zones → TEXT[], months/peak_months → INT[]
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
JSON_PATH = ROOT / "mushroom_catalog.json"
OUT_PATH = ROOT / "supabase/migrations/20260912000005_mushroom_catalog_seed.sql"

ALLOWED_EDIBILITY = {
    "edible", "conditionally_edible", "inedible", "poisonous", "deadly_poisonous"
}


def esc(s):
    if s is None:
        return "NULL"
    return "'" + str(s).replace("'", "''") + "'"


def esc_json(obj):
    if obj is None:
        return "NULL"
    s = json.dumps(obj, ensure_ascii=False)
    return "'" + s.replace("'", "''") + "'::jsonb"


def esc_text_array(arr):
    if not arr:
        return "'{}'::TEXT[]"
    items = ",".join('"' + str(x).replace('"', '\\"') + '"' for x in arr)
    return "'{" + items + "}'::TEXT[]"


def esc_int_array(arr):
    if not arr:
        return "'{}'::INT[]"
    items = ",".join(str(int(x)) for x in arr)
    return "'{" + items + "}'::INT[]"


def main():
    with open(JSON_PATH, encoding="utf-8") as f:
        data = json.load(f)

    species = data.get("species", [])
    lines = []
    lines.append("-- ============================================================================")
    lines.append("-- Seed mushroom_catalog — canonical 326-species catalog")
    lines.append("-- Auto-generated by scripts/generate_catalog_seed.py. Do not edit manually.")
    lines.append("-- ============================================================================")
    lines.append("")

    invalid_edibility = []

    for sp in species:
        sid = sp.get("id")
        if not sid:
            continue

        edibility = sp.get("edibility")
        if edibility not in ALLOWED_EDIBILITY:
            if edibility:
                invalid_edibility.append((sid, edibility))
            edibility = None

        photos_json = [{"url": u} for u in sp.get("photos", [])]

        values = [
            esc(sid),
            esc(sp.get("name", "")),
            esc(sp.get("latin", "")),
            esc(edibility) if edibility else "NULL",
            esc(sp.get("edibility_label", "")),
            "TRUE" if sp.get("red_listed") else "FALSE",
            esc(sp.get("rarity", "")),
            "TRUE" if sp.get("has_photo") else "FALSE",
            "TRUE" if sp.get("top20") else "FALSE",
            "TRUE" if sp.get("popular") else "FALSE",
            "TRUE" if sp.get("ai_recognition") else "FALSE",
            esc(sp.get("features", "")),
            esc_int_array(sp.get("months", [])),
            esc_json(sp.get("attrs", {})),
            esc_json(photos_json),
            esc_int_array(sp.get("peak_months", [])),
            esc_text_array(sp.get("zones", [])),
            esc_json(sp.get("license")) if sp.get("license") else "NULL",
            esc_json(sp.get("red_book_source")) if sp.get("red_book_source") else "NULL",
        ]

        lines.append(
            "INSERT INTO public.mushroom_catalog ("
            "id, name_ua, name_lat, edibility, edibility_label, "
            "red_listed, rarity, has_photo, top20, popular, ai_recognition, "
            "features, months, attrs, photos, peak_months, zones, license, red_book_source"
            ") VALUES ("
            + ", ".join(values) + ")"
            " ON CONFLICT (id) DO NOTHING;"
        )
        lines.append("")

    lines.append(f"-- Total species: {len(species)}")
    lines.append("")

    with open(OUT_PATH, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))

    print(f"Generated {OUT_PATH}")
    print(f"   species: {len(species)}")

    if invalid_edibility:
        print(f"WARNING invalid edibility ({len(invalid_edibility)}):")
        for sid, ed in invalid_edibility[:10]:
            print(f"   - {sid}: {ed}")
        print("   Written with edibility=NULL. Needs manual review.")


if __name__ == "__main__":
    main()
