#!/usr/bin/env python3
"""
Нормалізує id у mushroom_catalog.json: `-` -> `_`.
Також регенерує mushroom_catalog.js (той самий формат, що parse_zones.py).
Ідемпотентний: повторний запуск не змінює нічого.
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
JSON_PATH = ROOT / "mushroom_catalog.json"
JS_PATH = ROOT / "mushroom_catalog.js"


def normalize_id(s: str) -> str:
    return s.replace("-", "_").lower()


def main():
    if not JSON_PATH.exists():
        sys.exit(f"Not found {JSON_PATH}")

    with open(JSON_PATH, encoding="utf-8") as f:
        data = json.load(f)

    changed = 0
    for sp in data.get("species", []):
        old = sp.get("id", "")
        new = normalize_id(old)
        if old != new:
            sp["id"] = new
            changed += 1

    if changed == 0:
        print("Nothing to normalize - all ids already use underscores")
    else:
        print(f"Normalized {changed} ids")

    # Формат ідентичний scripts/parse_zones.py (indent=2, ensure_ascii=False)
    with open(JSON_PATH, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)

    js_content = (
        "// mushroom_catalog.js\n"
        "// Auto-generated by scripts/normalize_catalog_ids.py. Do not edit manually.\n"
        "window.MUSHROOM_CATALOG = "
        + json.dumps(data, ensure_ascii=False, separators=(",", ":"))
        + ";\n"
    )
    with open(JS_PATH, "w", encoding="utf-8") as f:
        f.write(js_content)

    print(f"Updated {JS_PATH.name}")

    invalid = [sp["id"] for sp in data["species"] if "-" in sp["id"]]
    if invalid:
        sys.exit(f"Still ids with '-': {invalid[:5]}")
    print(f"All {len(data['species'])} ids valid")


if __name__ == "__main__":
    main()
